"""Fix-bench cases and the developer's Eval-Kit suite. Pure.

A fix case is a past fix commit in the target repo, pinned at its parent. The developer
gets the defect as a bug report (never the fix), starts from a checkout of the parent,
and edits the working tree. The fix commit's own regression tests are held back: grading
applies the run's changed files to the parent, drops the held-back test files in on top,
and runs the case's test command (see `bench.fix.grade`).

A seeded case is blind: a bug planted in clean code by a patch (`seed`), committed as a
parentless commit so no history shows the diff (see `bench.fix.seed`). Its `fix` is the
clean commit, its `base` the seeded one, and its held-back tests live in the case dir.

The developer works in the same sandbox as a reviewer, with Edit and Write added: no
network but the crates.io hosts, and no read access to this repo, the target clone or
`~/.claude`, so neither the fix commit nor its tests are reachable.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from bench.prompt import sections
from bench.suite import HIDDEN, _list, _rule_path, _str

TOOLS = ("Read", "Grep", "Glob", "Bash", "Edit", "Write")
# Agent too: the bench has no reviewer subagent installed, and step 6 is out of scope.
DENIED_TOOLS = ("NotebookEdit", "WebFetch", "WebSearch", "Agent")
SAMPLES = 3
TIMEOUT_S = 3600
SHA = re.compile(r"^[0-9a-f]{40}$")
TASK = """\
{task}

Bench mode. The working directory is a checkout of {repo} at {base}; treat that commit as
`origin/main` and your base. There is no GitHub access: you cannot push, open a PR or run
the reviewer subagent, so skip the "Independent review" and "Open the PR" steps and leave
your change uncommitted in the working tree. Do everything else, then Return as the
prompt says, with status **ready for PR**."""
GENERATED = "# Generated by `python3 -m bench.fix suite {developer}`; edit the cases or prompt, not this.\n"


@dataclass(frozen=True)
class FixCase:
    id: str  # "<case set>/<case dir>"
    repo: str
    fix: str  # the real fix commit (or, seeded, the clean one); never shown to the developer
    base: str  # its parent (or, seeded, the seeded commit), where the developer starts
    task: str  # the defect as a bug report
    held_back: tuple[str, ...]  # test files added on top when grading
    test: tuple[str, ...]  # argv run at the repo root; exit 0 means fixed
    developer: str = ""
    seed: str = ""  # seeded only: the patch that plants the bug in `fix`
    hidden: tuple[tuple[str, str], ...] = ()  # seeded only: (path, text) of each held-back file
    # Existing tests the case's own defect breaks at the base, skipped in its suite steps so
    # the suite can pass there; the held-back tests and `fixed` still cover the defect.
    suite_skip: tuple[str, ...] = ()

    @property
    def seeded(self) -> bool:
        return bool(self.seed)


def parse_case(case_id: str, raw: dict, seed: str = "",
               hidden: dict[str, str] | None = None) -> FixCase:
    """`seed` and `hidden` are the texts of the files a seeded case names; the caller reads them."""
    known = {"developer", "repo", "fix", "base", "task", "held_back", "test", "source", "seed",
             "suite_skip"}
    unknown = set(raw) - known
    if unknown:
        raise ValueError(f"{case_id}: unknown keys {sorted(unknown)}")
    if bool(raw.get("seed")) != bool(seed):
        raise ValueError(f"{case_id}: seed names a patch, and the patch text is required")
    for key in ("fix", "base"):
        if not SHA.match(str(raw.get(key, ""))):
            raise ValueError(f"{case_id}: {key} must be a 40-character SHA")
    held, test = raw.get("held_back") or [], raw.get("test") or []
    if not held or not all(isinstance(p, str) and "tests/" in p for p in held):
        raise ValueError(f"{case_id}: held_back must list the fix's test files")
    if not test or not all(isinstance(a, str) for a in test):
        raise ValueError(f"{case_id}: test must be a non-empty argv list")
    skip = raw.get("suite_skip") or []
    if not isinstance(skip, list) or not all(isinstance(t, str) and t for t in skip):
        raise ValueError(f"{case_id}: suite_skip must list test names")
    task = str(raw.get("task", "")).strip()
    if not task:
        raise ValueError(f"{case_id}: task is empty")
    files = hidden or {}
    if seed and sorted(files) != sorted(held):
        raise ValueError(f"{case_id}: a seeded case needs the text of every held_back file")
    return FixCase(case_id, str(raw["repo"]), raw["fix"], raw["base"], task, tuple(held),
                   tuple(test), str(raw.get("developer", "")), seed,
                   tuple((p, files[p]) for p in held) if seed else (), tuple(skip))


def task_input(case: FixCase) -> str:
    return TASK.format(task=case.task, repo=case.repo, base=case.base)


def settings(domains: tuple[str, ...]) -> str:
    """Bash sandboxed or not at all; hidden paths unreadable and unwritable."""
    rules = [f"{verb}({_rule_path(p)}/**)" for p in HIDDEN for verb in ("Read", "Edit", "Write")]
    data = {
        "permissions": {"deny": [*DENIED_TOOLS, *rules]},
        "sandbox": {
            "enabled": True,
            "failIfUnavailable": True,
            "autoAllowBashIfSandboxed": True,
            "allowUnsandboxedCommands": False,
            "filesystem": {"denyRead": list(HIDDEN)},
            "network": {"allowedDomains": list(domains)},
        },
    }
    return json.dumps(data, indent=2) + "\n"


def prompt_toml(developer: str, prompt: str) -> str:
    """The Eval-Kit prompt spec, one section per `## ` heading, named by its slug."""
    lines = [GENERATED.format(developer=developer), "schema = 1", 'kind   = "prompt"',
             f'id     = "{developer}-developer"', f"tools  = {_list(TOOLS)}", ""]
    for heading, text in sections(prompt).items():
        lines += ["[[section]]", f"name = {_str(_slug(heading) or 'persona')}",
                  f"text = {_str(text)}", ""]
    return "\n".join(lines)


def suite_toml(developer: str, cases: list[FixCase], model: str, domains: tuple[str, ...]) -> str:
    head = [GENERATED.format(developer=developer), f"samples       = {SAMPLES}",
            f"allowed_tools = {_list(TOOLS)}", f"timeout       = {TIMEOUT_S}",
            f"settings      = '''\n{settings(domains)}'''", "",
            "[variant.baseline]", 'subject = "baseline.prompt.toml"', f"model   = {_str(model)}", ""]
    return "\n".join(head) + "\n" + "\n".join(_case(c) for c in cases)


def _case(case: FixCase) -> str:
    # The score of record is `bench.fix grade`; this check only says the run edited code.
    checkout = f'{{ from = "${{TARGET}}", head = "{case.base}" }}'
    return "\n".join([
        "[[case]]",
        f"id       = {_str(case.id.split('/', 1)[1])}",
        f"input    = {_str(task_input(case))}",
        f"checkout = {checkout}",
        'checks   = [{ any = [{ tool_called = "Edit" }, { tool_called = "Write" }] }]',
        "",
    ])


def _slug(heading: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
