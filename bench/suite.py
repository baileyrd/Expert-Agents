"""An expert's Eval-Kit suite, generated from its cases and its Claude subagent prompt. Pure.

The suite runs the prompt blind on every case: each run starts from a fresh checkout of
the case head (Eval-Kit's `checkout`), in Claude Code's sandbox with no network, and
cannot read this repo, the target clone or `~/.claude`. Each key finding becomes one judge
check, so `evalkit score --by-check` gives a first-pass recall per finding; the score of
record still comes from graded runs and `bench.scorer` (precision, severity).

The prompt is written into the prompt spec section by section, one per `## ` heading
named by its role in `expert.toml`, so `evalkit ablate` can drop one at a time.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

from bench.prompt import sections
from bench.scorer.model import Case, KeyFinding

TOOLS = ("Read", "Grep", "Glob", "Bash")
# Off whatever the domains hold: the sandbox's allowlist covers Bash only, and any web
# access reaches the live review on github.com.
DENIED_TOOLS = ("Edit", "Write", "NotebookEdit", "WebFetch", "WebSearch")
# Set by whoever runs the suite. EXPERT_AGENTS holds every answer key and the Eval-Kit
# store, TARGET the fix commits; ~/.claude holds transcripts that may discuss either.
HIDDEN = ("${EXPERT_AGENTS}", "${TARGET}", "~/.claude")
SAMPLES = 5
TIMEOUT_S = 3600
TASK = ("Review PR {pr} of {repo} against base {base} at head {head}. The working directory "
        "is a checkout of the head with history up to it, and its origin serves only the PR "
        "head ref.")
RUBRIC = """\
{id}: {title}
Pass if the review reports this known defect as one of its findings, even only in part
(for example one of several affected paths). Wording does not matter; the defect does.

{summary}
It counts as caught if the review {caught_if}"""
GENERATED = "# Generated by `python3 -m bench suite {expert}`; edit the cases or prompt, not this.\n"


@dataclass(frozen=True)
class Section:
    role: str
    text: str


def prompt_sections(prompt: str, roles: dict[str, str]) -> tuple[Section, ...]:
    """The prompt body split at its `## ` headings, each tagged with its declared role."""
    out = []
    for heading, text in sections(prompt).items():
        if heading not in roles:
            raise ValueError(f"section {heading!r} is not declared in expert.toml")
        out.append(Section(roles[heading], text))
    return tuple(out)


def prompt_toml(expert: str, parts: tuple[Section, ...]) -> str:
    """The Eval-Kit prompt spec: the sections in order, and the read-only tool set."""
    lines = [GENERATED.format(expert=expert), "schema = 1", 'kind   = "prompt"',
             f'id     = "{expert}"', f"tools  = {_list(TOOLS)}", ""]
    for part in parts:
        lines += ["[[section]]", f"name = {_str(part.role)}", f"text = {_str(part.text)}", ""]
    return "\n".join(lines)


def suite_toml(expert: str, cases: list[Case], model: str, domains: tuple[str, ...] = ()) -> str:
    """The suite: sandbox settings, the baseline variant, and one case per reviewed head."""
    by_id = {c.id: c for c in cases}
    head = [GENERATED.format(expert=expert), f"samples       = {SAMPLES}",
            f"allowed_tools = {_list(TOOLS)}", f"timeout       = {TIMEOUT_S}",
            f"settings      = '''\n{settings(domains)}'''", "",
            "[variant.baseline]", 'subject = "baseline.prompt.toml"', f"model   = {_str(model)}", ""]
    body = [_case(c, by_id.get(f"{expert}/{c.prior}") if c.prior else None) for c in cases]
    return "\n".join(head) + "\n" + "\n".join(body)


def settings(domains: tuple[str, ...]) -> str:
    """Claude Code settings: Bash sandboxed or not at all, hidden paths unreadable."""
    data = {
        "permissions": {"deny": [*DENIED_TOOLS, *(f"Read({_rule_path(p)}/**)" for p in HIDDEN)]},
        "sandbox": {
            "enabled": True,
            "failIfUnavailable": True,
            "autoAllowBashIfSandboxed": True,
            "allowUnsandboxedCommands": False,
            "filesystem": {"denyRead": list(HIDDEN)},
            "network": {"allowedDomains": list(domains)},
        },
    }
    return json.dumps(data, indent=2) + "\n"


def task(case: Case, prior: Case | None) -> str:
    text = TASK.format(pr=case.pr, repo=case.repo, base=case.base, head=case.head)
    if prior is None:
        return text
    listed = "\n".join(f"- {k.id} ({k.severity.name if k.severity else 'blocking'}): {k.title}"
                       for k in prior.key)
    return f"{text}\n\nPrior findings, from the review of {prior.head[:8]}; re-check each at this head:\n{listed}"


def rubric(key: KeyFinding) -> str:
    caught_if = key.caught_if[0].lower() + key.caught_if[1:]
    return RUBRIC.format(id=key.id, title=key.title, summary=key.summary.strip(),
                         caught_if=caught_if)


def _case(case: Case, prior: Case | None) -> str:
    checks = ",\n".join(f"  {{ judge = {_str(rubric(k))} }}" for k in case.key)
    checkout = (f'{{ from = "${{TARGET}}", head = "{case.head}", base = "{case.base}", '
                f'ref = "refs/pull/{case.pr}/head" }}')
    return "\n".join([
        "[[case]]",
        f"id       = {_str(case.id.split('/', 1)[1])}",
        f"input    = {_str(task(case, prior))}",
        f"checkout = {checkout}",
        f"checks   = [\n{checks},\n]",
        "",
    ])


def _rule_path(path: str) -> str:
    """A permission rule's path: `//abs` for an absolute path, `~/x` as written."""
    return path if path.startswith("~") else f"/{path}"


def _str(text: str) -> str:
    """A TOML basic string; JSON's escapes are all valid TOML."""
    return json.dumps(text, ensure_ascii=False)


def _list(items: tuple[str, ...]) -> str:
    return "[" + ", ".join(_str(i) for i in items) + "]"
