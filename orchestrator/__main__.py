"""Expert generator.

  python -m orchestrator new <name> --target-repo OWNER/REPO --axes N [--out DIR]
      Write expert.toml, prompt.md and codex.md: shared sections filled, the rest TODO.
  python -m orchestrator mine --target <clone> [--cases DIR] -- <path>...
      List the commits that answered reviews under <path>, held-out cases removed.
  python -m orchestrator codex <expert-dir>
      Rewrite codex.md from the finished prompt.md.
  python -m orchestrator check <expert-dir> [--cases DIR]
      Refuse an expert with TODOs, mismatched sections or a leaked answer-key PR.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

from bench.scorer.load import load_case
from bench.scorer.model import BenchError, Case

from . import check as checks
from . import mine as mining
from . import template

ROOT = Path(__file__).resolve().parent.parent
EXPERTS = ROOT / "experts"
CASES = ROOT / "bench" / "cases"


def main(argv: list[str]) -> int:
    args = _parser().parse_args(argv)
    try:
        return args.command(args)
    except (BenchError, ValueError, OSError) as err:
        print(f"error: {err}", file=sys.stderr)
        return 1


def new(args: argparse.Namespace) -> int:
    """Write the skeleton; refuse to touch an existing expert."""
    out: Path = args.out or EXPERTS / args.name
    if out.exists():
        raise ValueError(f"{out} exists; edit it, or write a variant elsewhere with --out")
    template.axes_heading(args.axes)
    out.mkdir(parents=True)
    source = f"Generated by orchestrator from {args.name}'s interview (interview.md)"
    (out / "expert.toml").write_text(template.manifest(args.name, args.target_repo, args.axes, source))
    (out / "prompt.md").write_text(template.subagent(args.name, args.axes))
    (out / "codex.md").write_text(template.codex(args.axes))
    print(out)
    return 0


def codex(args: argparse.Namespace) -> int:
    """Derive codex.md from prompt.md, so the two never drift apart."""
    expert_dir: Path = args.expert
    (expert_dir / "codex.md").write_text(template.codex_from((expert_dir / "prompt.md").read_text()))
    print(expert_dir / "codex.md")
    return 0


def mine(args: argparse.Namespace) -> int:
    paths = tuple(args.paths)
    if not paths:
        raise ValueError("name at least one path to mine after --")
    cases = _cases(args.cases)
    held = mining.held_out(args.target, cases)
    print(mining.grounding_md(mining.review_fixes(args.target, paths), held, paths), end="")
    return 0


def check(args: argparse.Namespace) -> int:
    expert_dir: Path = args.expert.resolve()
    manifest = _toml(expert_dir / "expert.toml")
    by_kind = {p["kind"]: (expert_dir / p["file"]).read_text() for p in manifest.get("prompt", [])}
    expert = checks.Expert(dir_name=expert_dir.name, manifest=manifest,
                           subagent=by_kind.get("claude-subagent", ""), codex=by_kind.get("codex", ""))
    cases = _cases(args.cases or CASES / expert_dir.name)
    found = checks.problems(expert, cases)
    for line in found:
        print(f"problem: {line}")
    for line in checks.notes(cases):
        print(f"note: {line}")
    print(f"{len(found)} problem(s), {len(cases)} case(s)")
    return 1 if found else 0


def _cases(cases_dir: Path | None) -> list[Case]:
    if cases_dir is None or not cases_dir.is_dir():
        return []
    return [load_case(d) for d in sorted(cases_dir.iterdir()) if (d / "pr.toml").is_file()]


def _toml(path: Path) -> dict:
    with path.open("rb") as f:
        return tomllib.load(f)


def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="python -m orchestrator", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(required=True)
    n = sub.add_parser("new", help="write a new expert's skeleton")
    n.set_defaults(command=new)
    n.add_argument("name", help="kebab-case, e.g. crypto; the subagent is <name>-expert")
    n.add_argument("--target-repo", required=True, help="OWNER/REPO the prompts sync to")
    n.add_argument("--axes", type=int, required=True, help="properties it protects, 2 to 5")
    n.add_argument("--out", type=Path, help="default experts/<name>")
    m = sub.add_parser("mine", help="review fixes in a domain, held-out cases removed")
    m.set_defaults(command=mine)
    m.add_argument("--target", type=Path, required=True, help="a local clone of the target repo")
    m.add_argument("--cases", type=Path, help="bench/cases/<expert>: their PRs are held out")
    m.add_argument("paths", nargs="*", help="paths in the target that make up the domain")
    x = sub.add_parser("codex", help="derive codex.md from prompt.md")
    x.set_defaults(command=codex)
    x.add_argument("expert", type=Path, help="experts/<name>, or a variant directory")
    c = sub.add_parser("check", help="refuse an expert that is not ready to bench")
    c.set_defaults(command=check)
    c.add_argument("expert", type=Path, help="experts/<name>, or a variant directory")
    c.add_argument("--cases", type=Path, help="default bench/cases/<dir name>")
    return p


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
